# ---------------------------------------------------------------- formatting
def fmt(value, ftype: str) -> str:
    if value is None:
        return ""
    if ftype == "decimal":
        return f"{float(value):.2f}"
    if ftype == "boolean":
        return "true" if value else "false"
    if ftype == "datetime":
        return value.strftime("%Y-%m-%dT%H:%M:%S")
    if ftype == "date":
        return value.isoformat()
    return str(value)


def parse(raw: str, ftype: str):
    if raw == "" or raw is None:
        return None
    if ftype == "integer":
        return int(raw)
    if ftype == "decimal":
        return float(raw)
    if ftype == "boolean":
        return raw.lower() == "true"
    if ftype == "date":
        return date.fromisoformat(raw)
    if ftype == "datetime":
        return datetime.fromisoformat(raw)
    return raw


def jsonable(value, ftype: str):
    if value is None:
        return None
    if ftype in ("date", "datetime"):
        return fmt(value, ftype)
    if ftype == "decimal":
        return round(float(value), 2)
    return value


# ---------------------------------------------------------------- writers
def write_csv(path: Path, table: Table, rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(table.field_names())
        for r in rows:
            w.writerow([fmt(r.get(f.name), f.type) for f in table.fields])


def write_json(path: Path, table: Table, rows: list[dict]) -> None:
    data = [{f.name: jsonable(r.get(f.name), f.type) for f in table.fields} for r in rows]
    path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


SQL_TYPES = {"string": "VARCHAR(255)", "integer": "INTEGER", "decimal": "NUMERIC(14,2)",
             "boolean": "BOOLEAN", "date": "DATE", "datetime": "TIMESTAMP"}


def ddl(table: Table, inline_fks: bool = True) -> str:
    cols = []
    for f in table.fields:
        col = f"  {f.name} {SQL_TYPES[f.type]}"
        if f.name == table.pk:
            col += " PRIMARY KEY"
        elif f.required:
            col += " NOT NULL"
        if f.unique and f.name != table.pk:
            col += " UNIQUE"
        cols.append(col)
    if inline_fks:
        cols += [f"  FOREIGN KEY ({f.name}) REFERENCES {f.fk.split('.')[0]}({f.fk.split('.')[1]})"
                 " DEFERRABLE INITIALLY DEFERRED" for f in table.fields if f.fk]
    return f"CREATE TABLE {table.name} (\n" + ",\n".join(cols) + "\n);"


def fk_alters(table: Table) -> list[str]:
    return [f"ALTER TABLE {table.name} ADD CONSTRAINT fk_{table.name}_{f.name} FOREIGN KEY ({f.name}) "
            f"REFERENCES {f.fk.split('.')[0]}({f.fk.split('.')[1]});" for f in table.fields if f.fk]


def sql_literal(value, ftype: str) -> str:
    if value is None:
        return "NULL"
    if ftype in ("integer",):
        return str(int(value))
    if ftype == "decimal":
        return f"{float(value):.2f}"
    if ftype == "boolean":
        return "TRUE" if value else "FALSE"
    return "'" + fmt(value, ftype).replace("'", "''") + "'"


def write_sql(path: Path, ds: dict, dialect: str = "sqlite", batch: int = 500) -> None:
    """Seed script. sqlite: inline FKs (SQLite resolves them lazily).
    postgres: create tables, insert, then ADD CONSTRAINT - which validates every row."""
    pg = dialect == "postgres"
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(f"-- Performance & Goals Platform seed data ({dialect}). Synthetic. Generated by data_generator.\n")
        fh.write("BEGIN;\n")
        for t in reversed(TABLES):
            fh.write(f"DROP TABLE IF EXISTS {t.name}{' CASCADE' if pg else ''};\n")
        for t in TABLES:
            fh.write(ddl(t, inline_fks=not pg) + "\n")
        for t in TABLES:
            rows = ds[t.name]
            names = ", ".join(t.field_names())
            for i in range(0, len(rows), batch):
                vals = ",\n".join("(" + ", ".join(sql_literal(r.get(f.name), f.type) for f in t.fields) + ")"
                                  for r in rows[i:i + batch])
                fh.write(f"INSERT INTO {t.name} ({names}) VALUES\n{vals};\n")
        if pg:
            for t in TABLES:
                for stmt in fk_alters(t):
                    fh.write(stmt + "\n")
        fh.write("COMMIT;\n")


def write_plain_csv(path: Path, columns: list[str], rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(columns)
        for r in rows:
            out = []
            for c in columns:
                v = r.get(c)
                if isinstance(v, list):
                    v = ";".join(v)
                elif isinstance(v, bool):
                    v = "true" if v else "false"
                elif isinstance(v, float):
                    v = f"{v:.2f}"
                out.append("" if v is None else v)
            w.writerow(out)


# ---------------------------------------------------------------- readers
def read_table(csv_dir: Path, name: str) -> list[dict]:
    table = TABLE_BY_NAME[name]
    types = {f.name: f.type for f in table.fields}
    with (csv_dir / f"{name}.csv").open(encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        return [{k: parse(v, types.get(k, "string")) for k, v in row.items()} for row in reader]


def read_dataset(data_dir: Path) -> dict:
    return {t.name: read_table(data_dir / "csv", t.name) for t in TABLES}


def read_ground_truth(data_dir: Path) -> list[dict]:
    with (data_dir / "ground_truth" / "ground_truth.csv").open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        r["related_ids"] = [x for x in r["related_ids"].split(";") if x]
        r["cycle_id"] = r["cycle_id"] or None
    return rows


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()
